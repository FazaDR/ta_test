# ======================================================================

def build_figure():
    """Create a single figure with both methods overlaid, x = node count."""

    fig, ax = plt.subplots(figsize=(9, 6.5))

    vigilances = sorted(BASE_DATA.keys())
    colors = plt.cm.viridis(
        [i / max(len(vigilances) - 1, 1) for i in range(len(vigilances))]
    )
    color_by_vigilance = dict(zip(vigilances, colors))

    for method_name, spec in METHODS.items():

        for vigilance, (nodes, times) in sorted(spec["data"].items()):

            ax.plot(
                nodes,
                times,
                marker=spec["marker"],
                markersize=4,
                linewidth=1.8,
                linestyle=spec["linestyle"],
                color=color_by_vigilance[vigilance],
                label=f"{method_name} (vigilance = {vigilance})",
            )

    ax.set_title("Base ATC-DT vs Free Area ATC-DT: Processing Time vs Node Count")
    ax.set_xlabel("Node count")
    ax.set_ylabel("Cumulative processing time (s)")
    ax.legend(fontsize=8, ncol=2)
    ax.grid(True, alpha=0.3)

    fig.tight_layout()

    return fig


def main():
    build_figure()
    plt.show()


if __name__ == "__main__":
    main()